  // 全角・半角をそろえ、小文字にして、カタカナをひらがなにする（比べるとき用）
  const fold = (s) => toHira(String(s || '').normalize('NFKC').toLowerCase());
  // 入力を整える：全角・半角をそろえ、ひらがな・カタカナの読みを、漢字の言葉に直す（それ以外の文字は、そのまま）
  const expand = (s) => {
    let n = String(s || '').normalize('NFKC');
    let h = toHira(n.toLowerCase());
    for (const [kana, kanji] of READINGS) {
      let i;
      while ((i = h.indexOf(kana)) !== -1) {
        n = n.slice(0, i) + kanji + n.slice(i + kana.length);
        h = h.slice(0, i) + toHira(kanji.toLowerCase()) + h.slice(i + kana.length);
      }
    }
    return n;
  };

  const api = { fold, expand, READINGS };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.HJFold = api;
